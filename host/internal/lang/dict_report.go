// one section of one report it has to be a single width, or the report reads
// as a list of accidents.  СИСТЕМА, ЗАГРУЗКА and ПАМЯТЬ share column 16, the
// header of a clean plan sits at 18, the trash counters of ЖУРНАЛ УБОРКИ at 20.
//
// # What is not here
//
// Разряды, приговоры, виды and имена неизмеренного arrive as VALUES from the
// core and from the collectors; they are words of the вокабула and live beside
// the договор, not here.  Numbers, bytes, percentages, dates and durations are
// not wordings either — they are written by the formatters of format.go, which
// is why a report holds no "%.1f" of its own.
