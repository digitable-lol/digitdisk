package lang

// Вокабула договора: слова, которыми экран называет значения решающего слоя.
//
// Разряд «Кэш», приговор «МожноУбрать», вид «Файл», якорь «ОтКорня» — это
// ИМЕНА в ядре на flang. Они там доказаны, они едут в JSON и в журнал, и ни
// одна буква из них здесь не меняется: переводится только слово, которым их
// называет экран, и живёт этот перевод на стороне хозяина. Потому вокабула
// заводится через addVocab: такое слово не написано в исходнике как литерал —
// оно приходит значением во время работы, и прогон, который ищет мёртвые
// статьи, обязан отличать одно от другого.
//
// Состав проверяется не на глаз: TestДоговорПереведёнСловами читает сами
// объявления (internal/core/contract.go, internal/protect/protect.go,
// internal/sysinfo/sysinfo.go) и требует слово для каждого имени. Новый
// разряд в ядре — это падающий прогон здесь, а не разряд по-русски в
// английском отчёте.
func init() {
	addVocab(map[string]string{
		// ── разряды (core.Class) ─────────────────────────────────────
		"Кэш":         "Cache",
		"Журнал":      "Log",
		"Сборка":      "Build",
		"Загрузка":    "Download",
		"Крупное":     "Large",
		"Неизвестное": "Unknown",

		// ── приговоры (core.Verdict) ─────────────────────────────────
		"МожноУбрать": "Removable",
		"Спросить":    "Ask",
		"НеТрогать":   "Keep",

		// ── виды (core.Kind) и то, что обход зовёт «Прочее» ──────────
		"Файл":    "File",
		"Каталог": "Dir",
		"Ссылка":  "Link",
		"Прочее":  "Other",

		// ── якоря справочника (core.Anchor) ──────────────────────────
		"ОтКорня":   "FromRoot",
		"ГдеУгодно": "Anywhere",

		// ── виды правил защитного списка (protect.Kind) ──────────────
		"путь":   "path",
		"разряд": "class",

		// ── имена неизмеренного (sysinfo.Fact*) ──────────────────────
		"загрузка ЦП":                   "CPU load",
		"очередь планировщика":          "scheduler queue",
		"потоки процессов":              "process threads",
		"заблокированные процессы":      "blocked processes",
		"процессорное время процессов":  "process CPU time",
		"память процессов":              "process memory",
		"выполняющиеся процессы":        "running processes",
		"командные строки процессов":    "process command lines",
		"процессы других пользователей": "other users' processes",
		"счётчики интерфейсов":          "interface counters",
		"отброшенные исходящие пакеты":  "dropped outgoing packets",
		"датчики температуры":           "temperature sensors",
		"разбивка памяти":               "memory breakdown",
	})
}

// Ещё вокабула: значения, которые хозяин печатает как есть, потому что их
// сочинил не он.
//
// Имя решающего слоя приходит от самого слоя и едет в JSON и в журнал
// значением поля «решающий_слой» — там оно обязано остаться собой. Источник
// справочника («встроенный») — то же самое: поле «справочник» и «откуда».
// Переводится, как и разряд, только слово на экране.
func init() {
	addVocab(map[string]string{
		"заглушка (решающий слой ещё не подключён)": "stub (no decision layer wired in)",
		"flang «Опись диска» (core/out-go)":         "flang «Опись диска» (core/out-go)",
		"встроенный":                  "built-in",
		"выключен ключом --no-places": "off, by --no-places",
	})
}

// И ещё вокабула: кто решил язык этого прогона. Печатает её --version, и
// печатает потому, что «почему инструмент говорит на этом языке» — вопрос, у
// которого должен быть ответ, называющий файл или переменную.
func init() {
	addVocab(map[string]string{
		"спрошено":  "asked",
		"локаль":    "locale",
		"умолчание": "default",
	})
}
