/**
 * Постусловия ядра «Опись диска» — приписываются к AST, а не к исходнику.
 *
 * ПОЧЕМУ ТАК. Поверхность flang формы для постусловия функции НЕ ИМЕЕТ:
 * `parseFunction` (flang/src/parser.mjs:1115) знает у функции только
 * `принимает`, `возвращает`, `убывает`, `пример` и тело, а слово «свойство»
 * внутри `функция` даёт FLANG_PARSE («'свойство' не начинает выражение»).
 * Поле `postconditions` при этом — часть контракта AST (flang/SPEC.md:743,
 * раздел «Постусловия функции»), и его читают ВСЕ слои: интерпретатор
 * (src/interpret.mjs:594) и все восемь бэкендов печати (например
 * src/emit/go.mjs:884 и src/emit/c.mjs:894). Единственный путь из «постусловие
 * записано» в «постусловие проверяется» — приписать его к AST.
 *
 * Выражение постусловия — обычный `Expr`, поэтому каждое из них здесь всего
 * один узел `call`: само правило написано на flang, тотальной функцией с
 * примерами, и живёт в core/opis-diska.flang.
 *
 *   node core/postconditions.mjs → core/opis-diska.ast.json
 */
import { writeFileSync } from "node:fs"
import { dirname, join } from "node:path"
import { fileURLToPath } from "node:url"

import { loadProgram } from "/home/b/projects/flang/flang/bin/flang.mjs"

const здесь = dirname(fileURLToPath(import.meta.url))
const источник = join(здесь, "opis-diska.flang")
const цель = join(здесь, "opis-diska.ast.json")

const КОД = "DIGITDISK_RULE"
const переменная = (имя) => ({ kind: "var", name: имя })
const вызов = (имя, ...аргументы) => ({ kind: "call", name: имя, args: аргументы })
const результат = переменная("результат")

/** Постусловие: имя, выражение и текст отказа. `bind` всегда «результат». */
function правило(имя, expr) {
  return {
    name: имя,
    bind: "результат",
    expr,
    code: КОД,
    message: `нарушено постусловие «${имя}» ядра «Опись диска»`,
  }
}

const ПОСТУСЛОВИЯ = {
  /* Р1–Р6: разряд обязан иметь примету, и порядок правил выражен явно. */
  "Разряд находки": [
    правило("Разряд обоснован приметой", вызов("Разряд обоснован", переменная("находка"), результат)),
  ],
  /* П3 отдельно: каталог из убираемого разряда убирать нельзя. */
  "Приговор мусора": [
    правило("Каталог не убирается", {
      kind: "if",
      cond: вызов("Каталог", переменная("находка")),
      then: { kind: "if", cond: вызов("Это МожноУбрать", результат), then: { kind: "literal", value: false }, else: { kind: "literal", value: true } },
      else: { kind: "literal", value: true },
    }),
  ],
  /* П1–П9, включая И1 на уровне одной записи. */
  "Приговор находки": [
    правило(
      "Приговор обоснован",
      вызов("Приговор обоснован", переменная("находка"), переменная("разряд"), результат),
    ),
  ],
  /* В1–В2. */
  "Вес находки": [
    правило("Вес обоснован", вызов("Вес обоснован", переменная("находка"), переменная("приговор"), результат)),
  ],
  /* И1 — на одном решении. */
  "Решить находку": [правило("И1: убрать можно только мусор", вызов("И1 держится", результат))],
  /* И1 — на всей описи. */
  "Решить всё": [правило("И1 всюду: убрать можно только мусор", вызов("И1 держится всюду", результат))],
  /* И2 — свёртка не обещает больше, чем есть у убираемых записей. */
  Свести: [правило("И2: освобождаемое не больше убираемого", вызов("И2 держится", переменная("записи"), результат))],
  /* Отчёт ничего не теряет и не выдумывает. */
  "Отчёт": [правило("Отчёт той же длины", вызов("Отчёт той же длины", переменная("записи"), результат))],
}

const программа = await loadProgram(источник)
let приписано = 0
for (const функция of программа.functions ?? []) {
  const список = ПОСТУСЛОВИЯ[функция.name]
  if (список === undefined) continue
  функция.postconditions = список
  приписано += список.length
}

const необъявленные = Object.keys(ПОСТУСЛОВИЯ).filter(
  (имя) => (программа.functions ?? []).every((функция) => функция.name !== имя),
)
if (необъявленные.length > 0) throw new Error(`в модуле нет функций: ${необъявленные.join(", ")}`)

writeFileSync(цель, `${JSON.stringify(программа, null, 2)}\n`, "utf8")
process.stdout.write(`${JSON.stringify({ источник, цель, постусловий: приписано, функций: Object.keys(ПОСТУСЛОВИЯ).length })}\n`)
